#!/usr/bin/env bun
import { createHash } from "node:crypto";
import { rename, rm, writeFile } from "node:fs/promises";
import { normalizeOpenCodeModel, OPENCODE_CATALOG_URLS } from "../open-sse/config/opencodeCatalog.js";

const MAX_BYTES = 4 * 1024 * 1024;
const target = new URL("../open-sse/providers/metadata/opencodeCatalogData.js", import.meta.url);
const temporary = new URL(`${target.href}.${process.pid}.tmp`);

async function capture(product, url) {
  const response = await fetch(url, { redirect: "error", signal: AbortSignal.timeout(15000) });
  if (!response.ok || Number(response.headers.get("content-length")) > MAX_BYTES) {
    throw new Error(`Unable to read OpenCode ${product} catalog (HTTP ${response.status})`);
  }
  const bytes = new Uint8Array(await response.arrayBuffer());
  if (bytes.length > MAX_BYTES) throw new Error(`OpenCode ${product} catalog is too large`);
  const { data } = JSON.parse(new TextDecoder().decode(bytes));
  const models = Array.isArray(data) ? data.map(row => normalizeOpenCodeModel(row, product)) : [];
  if (!models.length || models.some(model => !model?.pricing || model.pricing.input === null || model.pricing.output === null)
    || new Set(models.map(model => model.id)).size !== models.length) {
    throw new Error(`Unrecognized OpenCode ${product} catalog. The previous snapshots were retained.`);
  }
  const source = { url, verifiedAtUtc: new Date().toISOString(), sha256: createHash("sha256").update(bytes).digest("hex") };
  const name = product === "zen" ? "openCodeZenCatalog" : "openCodeGoCatalog";
  console.log(`${name}: ${models.length} models`);
  return [`export const ${name} = {`, `  source: ${JSON.stringify(source)},`, "  models: [",
    ...models.map(model => `    ${JSON.stringify(model)},`), "  ],", "};", ""].join("\n");
}

const catalogs = await Promise.all(Object.entries(OPENCODE_CATALOG_URLS).map(([product, url]) => capture(product, url)));
try {
  await writeFile(temporary, [
    "// Generated by scripts/refresh-opencode-catalog.mjs from public OpenCode catalogs.",
    "// Rates are USD per million tokens; OpenCode Go rates are quota references.",
    ...catalogs,
  ].join("\n"), { flag: "wx" });
  await rename(temporary, target);
} finally {
  await rm(temporary, { force: true });
}
